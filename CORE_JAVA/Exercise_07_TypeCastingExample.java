public class Exercise_07_TypeCastingExample {
    public static void main(String[] args) {

        double d = 12.56;
        int i = (int)d;

        System.out.println("Double = " + d);
        System.out.println("Int = " + i);

        int num = 100;
        double result = (double)num;

        System.out.println("Converted Double = " + result);
    }
}